"""
Vendors boost/lockfree/spsc_value.hpp (and the Boost headers it needs) into crospi_core/include/crospi_boost.

The copied headers are renamed so they can never clash with the system Boost that is included in the same
translation unit (e.g. through eTaSL/KDL):
  - include paths  boost/...   -> crospi_boost/...
  - namespaces     boost::     -> crospi_boost::   (and MPL's ADL barrier namespace mpl_ -> crospi_mpl_)
  - macros         BOOST_*     -> CROSPI_BOOST_*   (every occurrence, also inside identifiers, since
                                                    Boost.Preprocessor builds macro names by token pasting)

The set of headers is the one that GCC actually includes (C++17 and C++20) plus the complete boost/config and
boost/predef directories, which contain the compiler and platform specific branches.

Usage: vendor_boost.py <boost_include_dir> <output_include_dir>
  e.g. vendor_boost.py /opt/boost_1.89.0/include crospi_core/include
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile

ENTRY_HEADER = "boost/lockfree/spsc_value.hpp"
FULL_DIRECTORIES = ["boost/config", "boost/predef"]
CXX_STANDARDS = ["c++17", "c++20"]

RENAMES = [
    (re.compile(r"(?<![A-Za-z0-9_])boost/"), "crospi_boost/"),
    (re.compile(r"BOOST_"), "CROSPI_BOOST_"),
    (re.compile(r"(?<![A-Za-z0-9_])boost(?=\s*::)"), "crospi_boost"),
    (re.compile(r"(?<![A-Za-z0-9_])namespace(\s+)boost(?![A-Za-z0-9_])"), r"namespace\1crospi_boost"),
    (re.compile(r"(?<![A-Za-z0-9_])mpl_(?![A-Za-z0-9_])"), "crospi_mpl_"),
]


def used_headers(boost_include):
    """Returns the Boost headers (relative to boost_include) that the compiler includes for ENTRY_HEADER."""
    headers = set()
    with tempfile.TemporaryDirectory() as tmp:
        test_file = os.path.join(tmp, "spsc_value_test.cpp")
        with open(test_file, "w") as f:
            f.write(f"#include <{ENTRY_HEADER}>\n")
        prefix = os.path.join(os.path.realpath(boost_include), "")
        for std in CXX_STANDARDS:
            result = subprocess.run(
                ["g++", f"-std={std}", "-I", boost_include, "-H", "-fsyntax-only", test_file],
                capture_output=True, text=True, check=True)
            for line in result.stderr.splitlines():
                path = os.path.realpath(line.lstrip(". ").strip())
                if path.startswith(prefix):
                    headers.add(os.path.relpath(path, prefix))
    for directory in FULL_DIRECTORIES:
        for root, _, files in os.walk(os.path.join(boost_include, directory)):
            headers.update(os.path.relpath(os.path.join(root, f), boost_include) for f in files)
    return sorted(headers)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    boost_include, output_include = sys.argv[1:3]
    output_dir = os.path.join(output_include, "crospi_boost")
    if os.path.exists(output_dir):
        shutil.rmtree(output_dir)

    headers = used_headers(boost_include)
    for header in headers:
        with open(os.path.join(boost_include, header), encoding="latin-1") as f:
            text = f.read()
        for regex, replacement in RENAMES:
            text = regex.sub(replacement, text)
        destination = os.path.join(output_dir, header[len("boost/"):])
        os.makedirs(os.path.dirname(destination), exist_ok=True)
        with open(destination, "w", encoding="latin-1") as f:
            f.write(text)

    with open(os.path.join(boost_include, "boost/version.hpp")) as f:
        version = re.search(r'BOOST_LIB_VERSION\s+"([0-9_]+)"', f.read()).group(1).replace("_", ".")
    with open(os.path.join(output_dir, "VENDORED_FROM.txt"), "w") as f:
        f.write(f"Boost {version}, entry header {ENTRY_HEADER}, generated by crospi_core/tools/vendor_boost/vendor_boost.py\n")
    print(f"Vendored {len(headers)} headers of Boost {version} into {output_dir}")


if __name__ == "__main__":
    main()
